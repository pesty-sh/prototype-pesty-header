"""The rest of the printable ASCII for the Pesty face.

`engine/mark.py` owns the hand-drawn `p e s t y . h`. This file is every
other printable ASCII character. Capitals are not here: the page folds
them onto these lowercase letters.

Every glyph is 19 rows.

- Rows 0–4 are the ascender.
- Rows 5–14 are the x-height, where `e` and `s` live.
- Rows 15–18 are the descender, where `p` and `y` live.

`#` is ink. `.` is empty. A row that is the wrong width will not import.
"""

from __future__ import annotations


def _take(art: str) -> list[str]:
    lines = art.split("\n")
    if lines and lines[0] == "":
        lines = lines[1:]
    if lines and lines[-1] == "":
        lines = lines[:-1]
    if len(lines) != 19:
        raise ValueError(f"expected 19 rows, got {len(lines)}")
    width = len(lines[0])
    for index, line in enumerate(lines):
        if len(line) != width:
            raise ValueError(f"row {index} is {len(line)} wide, expected {width}: {line}")
        bad = set(line) - set("#.")
        if bad:
            raise ValueError(f"row {index} has {bad}: {line}")
    return lines


EXTRA: dict[str, list[str]] = {}


def _add(char: str, art: str) -> None:
    if len(char) != 1:
        raise ValueError(char)
    EXTRA[char] = _take(art)


